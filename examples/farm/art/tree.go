// crown is the tree's crown leant lean pixels in the wind, its outline
// kept: the leaves inside move, the edge does not jump.
func crown(lean int) Grid {
	if lean == 0 {
		return treeCrown
	}
	out := treeCrown.copyOf()
	for y := 3; y < 13; y++ {
		r := []rune(treeCrown[y])
		for x := 1; x < Size-1; x++ {
			if r[x] != 'k' && r[x] != '.' {
				src := x - lean
				if s := []rune(treeCrown[y])[src]; s != 'k' && s != '.' {
					r[x] = s
				}
			}
		}
		out[y] = string(r)
	}
	return out
}
