// sway is a crop's ripe stage with its leaves blown a pixel over: the
// rows above the fruit move, the fruit stays put.
func sway(g Grid, rows int) Grid {
	out := g.copyOf()
	for y := 0; y < rows; y++ {
		out[y] = "." + g[y][:Size-1]
	}
	return out
}
