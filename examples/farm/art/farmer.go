// step is a farmer's frame with its legs, the last three rows, swapped
// for legs mid-stride.
func step(g Grid, legs string) Grid {
	out := g.copyOf()
	copy(out[Size-3:], grid(legs))
	return out
}

// hold is a farmer's frame holding the watering can, pouring.
func hold(g Grid, can string) Grid {
	return over(g, grid(can))
}

