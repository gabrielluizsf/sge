package gots

import (
	"go/ast"
	"go/token"
	"go/types"
	"path"
	"sort"
	"strings"
)

// module writes the TypeScript module for files of the package. tests are
// the names of test functions to register with the testing package.
func (e *emitter) module(files []*ast.File) string {
	scope := e.tpkg.Scope()
	for _, n := range scope.Names() {
		e.pkgNames[mangle(n)] = true
	}
	for _, f := range files {
		for _, imp := range f.Imports {
			if obj := e.info.Implicits[imp]; obj != nil {
				e.importAlias(obj.(*types.PkgName).Imported())
			} else if imp.Name != nil {
				if obj, ok := e.info.Defs[imp.Name].(*types.PkgName); ok {
					e.importAlias(obj.Imported())
				}
			}
		}
	}
	e.files = files
	e.findBoxed(files)
	e.boxedDone = map[*types.Info]bool{e.info: true}

	var td typeDecls
	methods := e.methodsOf(files)
	for _, tn := range sortedTypes(scope) {
		if !inFiles(e.prog.Fset, tn.Pos(), files) || e.generic(tn) {
			continue
		}
		e.typeDecl(&td, tn, methods[tn])
	}

	var funcs, vars, inits writer
	var initFuncs []string
	var tests []string
	for _, f := range files {
		for _, d := range f.Decls {
			switch d := d.(type) {
			case *ast.FuncDecl:
				if d.Recv != nil || d.Type.TypeParams != nil {
					continue
				}
				fn := e.info.Defs[d.Name].(*types.Func)
				name := mangle(d.Name.Name)
				if d.Name.Name == "init" {
					name = "init$" + itoa(len(initFuncs)+1)
					initFuncs = append(initFuncs, name)
				}
				e.function(&funcs, "export function "+name, fn.Type().(*types.Signature), d.Type, d.Body, nil, false, true)
				funcs.line("")
				if isTest(d, fn) {
					tests = append(tests, name)
				}
			case *ast.GenDecl:
				if d.Tok == token.CONST {
					e.constDecl(&vars, d)
				}
			}
		}
	}
	e.varDecls(&vars, &inits, files)
	var instFuncs writer
	e.emitInstances(&td, &instFuncs)
	for _, n := range initFuncs {
		inits.line("%s();", n)
	}
	if e.tpkg.Name() == "main" && len(tests) == 0 {
		inits.line("main();")
	}
	if len(tests) > 0 {
		alias := e.imports["testing"]
		for _, t := range tests {
			inits.line("%s.register(%q, %s);", alias, t, t)
		}
	}

	var out writer
	out.line("// Code generated by gots from %s. DO NOT EDIT.", e.pkg.Path)
	out.line("// @ts-nocheck: the Go type checker already checked this module; its")
	out.line("// annotations are for the TypeScript that imports it.")
	out.line("// deno-lint-ignore-file")
	out.line("import * as $ from %q;", rel(e.dir, path.Join(runtimeDir, "mod.ts")))
	for _, p := range e.importOrder {
		dep := e.prog.Packages[p]
		target := "_gots/std/" + p + "/mod.ts"
		if dep != nil {
			target = e.lay.file(dep)
		}
		out.line("import * as %s from %q;", e.imports[p], rel(e.dir, target))
	}
	out.line("")
	section := func(w *writer) {
		if s := w.String(); s != "" {
			out.b.WriteString(s)
			out.line("")
		}
	}
	section(&e.anonDecls)
	section(&td.classes)
	section(&td.descs)
	var consts writer
	for _, d := range e.typeOrder {
		consts.line("const %s = %s;", e.typeConsts[d], d)
	}
	section(&consts)
	section(&td.funcs)
	section(&instFuncs)
	section(&funcs)
	section(&vars)
	section(&inits)
	return strings.TrimRight(out.String(), "\n") + "\n"
}

func inFiles(fset *token.FileSet, pos token.Pos, files []*ast.File) bool {
	for _, f := range files {
		if f.FileStart <= pos && pos <= f.FileEnd {
			return true
		}
	}
	return false
}

// isTest reports whether d is a Go test function, func TestX(t *testing.T).
func isTest(d *ast.FuncDecl, fn *types.Func) bool {
	if !strings.HasPrefix(d.Name.Name, "Test") || d.Name.Name == "TestMain" {
		return false
	}
	sig := fn.Type().(*types.Signature)
	if sig.Params().Len() != 1 || sig.Results().Len() != 0 {
		return false
	}
	return typeString(sig.Params().At(0).Type()) == "*testing.T"
}

// constDecl exports a package's constants, for TypeScript code; Go code
// gets them written out where it uses them.
func (e *emitter) constDecl(w *writer, d *ast.GenDecl) {
	for _, spec := range d.Specs {
		for _, id := range spec.(*ast.ValueSpec).Names {
			c, ok := e.info.Defs[id].(*types.Const)
			if !ok || id.Name == "_" {
				continue
			}
			w.line("export const %s: %s = %s;", mangle(id.Name), e.tsType(c.Type()), e.constant(c.Val(), c.Type()))
		}
	}
}

// varDecls declares the package's variables at their zero values, with a
// setter for other modules, then runs their initializers in Go's order.
func (e *emitter) varDecls(decls, inits *writer, files []*ast.File) {
	var vs []*types.Var
	for _, f := range files {
		for _, d := range f.Decls {
			g, ok := d.(*ast.GenDecl)
			if !ok || g.Tok != token.VAR {
				continue
			}
			for _, spec := range g.Specs {
				for _, id := range spec.(*ast.ValueSpec).Names {
					if v, ok := e.info.Defs[id].(*types.Var); ok && id.Name != "_" {
						vs = append(vs, v)
					}
				}
			}
		}
	}
	sort.SliceStable(vs, func(i, j int) bool { return vs[i].Pos() < vs[j].Pos() })
	for _, v := range vs {
		n := mangle(v.Name())
		decls.line("export let %s: %s = %s;", n, e.tsType(v.Type()), e.zero(v.Type()))
		decls.line("export function %s$set(v: %s): void { %s = v; }", n, e.tsType(v.Type()), n)
	}
	e.sc = newScope(e.pkgNames)
	e.fn = &funcState{sig: types.NewSignatureType(nil, nil, nil, nil, nil, false)}
	for _, in := range e.info.InitOrder {
		if !inFiles(e.prog.Fset, in.Lhs[0].Pos(), files) {
			continue
		}
		if len(in.Lhs) == 1 {
			v := in.Lhs[0]
			if v.Name() == "_" {
				inits.line("%s;", e.expr(in.Rhs))
				continue
			}
			inits.line("%s;", e.setOf(mangle(v.Name()), e.value(in.Rhs, v.Type()), v.Type()))
			continue
		}
		t := e.newTmp()
		inits.line("const %s = %s;", t, e.expr(in.Rhs))
		for i, v := range in.Lhs {
			if v.Name() != "_" {
				inits.line("%s = %s[%d];", mangle(v.Name()), t, i)
			}
		}
	}
	e.sc, e.fn = nil, nil
}
