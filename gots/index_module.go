package gots

import (
	"path"
	"sort"
)

// indexModule exports the requested packages by name, with what
// TypeScript needs at the boundary: Go strings are bytes, so text crosses
// through goString and jsString, and a Go slice is made from an array with
// goSlice.
func indexModule(prog *Program, lay layout) string {
	var w writer
	w.line("// Code generated by gots. DO NOT EDIT.")
	w.b.WriteString(jsdoc("The Go packages of this module, transpiled to TypeScript: each export is one of them, by its name. goString and jsString carry text into and out of Go strings, and goSlice makes a Go slice of an array.", "", "@module"))
	w.line("export { toGo as goString, fromGo as jsString } from %q;", "./"+path.Join(runtimeDir, "string.ts"))
	w.line("export { fromArray as goSlice, Slice } from %q;", "./"+path.Join(runtimeDir, "slice.ts"))
	taken := map[string]bool{"goString": true, "jsString": true, "goSlice": true, "Slice": true}
	roots := append([]*Package(nil), prog.Roots...)
	sort.Slice(roots, func(i, j int) bool { return roots[i].Path < roots[j].Path })
	for _, p := range roots {
		if p.Name == "main" {
			continue
		}
		name := mangle(p.Name)
		for i := 2; taken[name]; i++ {
			name = mangle(p.Name) + itoa(i)
		}
		taken[name] = true
		w.line("export * as %s from %q;", name, rel(".", lay.file(p)))
	}
	return w.String()
}
