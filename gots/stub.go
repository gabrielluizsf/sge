package gots

import (
	"go/types"
	"path"
	"strings"
)

// stubModule is the module of a package gots does not transpile: every
// exported name is there, so code that imports the package loads, and
// using any of it panics saying why.
func stubModule(p *Package) string {
	var w writer
	w.line("// Code generated by gots: %s is not supported, and using it panics.", p.Path)
	w.line("// @ts-nocheck")
	w.line("// deno-lint-ignore-file")
	w.line("import * as $ from %q;", rel("_gots/std/"+p.Path, path.Join(runtimeDir, "mod.ts")))
	msg := jsString("gots: package " + p.Path + " needs goroutines, which are not supported yet")
	w.line("const unsupported = (..._a: any[]): any => $.panic(%s);", msg)
	scope := p.Types.Scope()
	for _, n := range scope.Names() {
		if !token_IsExported(n) {
			continue
		}
		name := mangle(n)
		switch obj := scope.Lookup(n).(type) {
		case *types.Func:
			w.line("export const %s = unsupported;", name)
		case *types.Var:
			w.line("export let %s: any = null;", name)
		case *types.Const:
			e := &emitter{}
			w.line("export const %s = %s;", name, e.constantPlain(obj))
		case *types.TypeName:
			switch {
			case isStruct(obj.Type()):
				w.line("export class %s extends $.Native {}", name)
				w.line("$.nativeType(%q, %s);", p.Types.Name()+"."+n, name)
			case isInterface(obj.Type()):
				w.line("export const %s$type = $.ifaceType(%q, []);", name, p.Types.Name()+"."+n)
			default:
				w.line("export const %s$type = $.named(%q, $.Int, null);", name, p.Types.Name()+"."+n)
			}
		}
	}
	return w.String()
}

func token_IsExported(n string) bool {
	return n != "" && strings.ToUpper(n[:1]) == n[:1] && n[0] != '_'
}

// constantPlain writes a package constant without an emitter's context.
func (e *emitter) constantPlain(c *types.Const) string {
	if isInterface(c.Type()) || basicKind(c.Type()) == types.Invalid {
		return "null"
	}
	return e.constant(c.Val(), c.Type())
}
